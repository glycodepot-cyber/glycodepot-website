export interface ChemistryProfile {
  cas: string;
  formula: string;
  molecularWeight: number;
}

const PARSED: Record<string, readonly [string, number]> = (() => {
  const map: Record<string, readonly [string, number]> = {};
  for (const line of TABLE.trim().split("\n")) {
    const [formula, weight, casList] = line.split("|");
    const mw = Number(weight);
    if (!formula || !Number.isFinite(mw) || !casList) continue;
    for (const cas of casList.split(",")) {
      if (cas) map[cas] = [formula, mw];
    }
  }
  return map;
})();

/** Verified chemistry for a bare CAS number, or null when we hold no record. */
export function chemistryForCas(cas: string | null | undefined): ChemistryProfile | null {
  if (!cas) return null;
  const row = PARSED[cas];
  return row ? { cas, formula: row[0], molecularWeight: row[1] } : null;
}
