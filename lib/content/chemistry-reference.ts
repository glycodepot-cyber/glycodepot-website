const CAS_PATTERN = /\b(\d{2,7}-\d{2}-\d)\b/;

export interface ChemistryProfile {
  cas: string;
  formula: string;
  molecularWeight: number;
}

const PARSED: Record<string, readonly [string, number]> = (() => {
  const map: Record<string, readonly [string, number]> = {};
  for (const line of TABLE.trim().split("\n")) {
    const [cas, formula, mw] = line.split("|");
    const weight = Number(mw);
    if (cas && formula && Number.isFinite(weight)) map[cas] = [formula, weight];
  }
  return map;
})();

/** The CAS number already present in a product's own name or slug, if any. */
export function casFromProduct(product: { name: string; slug: string }): string | null {
  const match = CAS_PATTERN.exec(`${product.name} ${product.slug}`);
  return match ? match[1] : null;
}

/**
 * Verified chemistry for a product, or null when we hold no PubChem record for
 * its CAS. Callers must present null as "not published" - never as a blank row
 * in a specification table and never as a generated value.
 */
export function chemistryProfile(product: { name: string; slug: string }): ChemistryProfile | null {
  const cas = casFromProduct(product);
  if (!cas) return null;
  const row = PARSED[cas];
  if (!row) return null;
  return { cas, formula: row[0], molecularWeight: row[1] };
}
